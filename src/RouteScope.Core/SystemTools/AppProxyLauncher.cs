using System.Diagnostics;
using System.Text;

namespace RouteScope.Core.SystemTools;

/// <summary>
/// Launches an application so that it — and only it — uses the proxy. Three mechanisms,
/// picked per app: environment variables, the Chromium/Electron command line switch, and a
/// generated Firefox profile. No driver, no system-wide changes.
/// </summary>
public sealed class AppProxyLauncher
{
    private readonly List<int> _launched = new();

    public int MixedPort { get; }

    public AppProxyLauncher(int mixedPort) => MixedPort = mixedPort;

    public string HttpUrl => $"http://127.0.0.1:{MixedPort}";
    public string SocksUrl => $"socks5://127.0.0.1:{MixedPort}";

    public IReadOnlyList<int> LaunchedPids => _launched;

    /// <summary>How RouteScope expects to reach this app, for the UI to explain itself.</summary>
    public string DescribeMechanism(string exePath)
    {
        var name = Path.GetFileName(exePath);
        if (IsFirefox(name)) return "Firefox profile";
        if (IsChromiumFamily(exePath)) return "Chromium switch + environment";
        return "Environment variables";
    }

    public Process? Launch(string exePath, string? arguments = null, bool addBrowserSwitch = true)
    {
        if (!File.Exists(exePath))
        {
            LogBus.Warn("launch", "Not found: " + exePath);
            return null;
        }

        try
        {
            var name = Path.GetFileName(exePath);
            var args = arguments ?? "";

            if (addBrowserSwitch && IsChromiumFamily(exePath))
            {
                var flag = $"--proxy-server={HttpUrl}";
                if (!args.Contains("--proxy-server", StringComparison.OrdinalIgnoreCase))
                    args = string.IsNullOrWhiteSpace(args) ? flag : args + " " + flag;
            }
            else if (addBrowserSwitch && IsFirefox(name))
            {
                var profile = WriteFirefoxProfile();
                var flag = $"-no-remote -profile \"{profile}\"";
                if (!args.Contains("-profile", StringComparison.OrdinalIgnoreCase))
                    args = string.IsNullOrWhiteSpace(args) ? flag : args + " " + flag;
            }

            var psi = new ProcessStartInfo(exePath, args)
            {
                UseShellExecute = false,
                WorkingDirectory = Path.GetDirectoryName(exePath) ?? Environment.CurrentDirectory,
            };

            ApplyProxyEnvironment(psi);

            var process = Process.Start(psi);
            if (process is not null)
            {
                _launched.Add(process.Id);
                LogBus.Info("launch", $"Started {name} (pid {process.Id}) via {DescribeMechanism(exePath)}");
            }
            return process;
        }
        catch (Exception ex)
        {
            LogBus.Error("launch", $"Could not start {exePath}: {ex.Message}");
            return null;
        }
    }

    public void ApplyProxyEnvironment(ProcessStartInfo psi)
    {
        psi.Environment["HTTP_PROXY"] = HttpUrl;
        psi.Environment["HTTPS_PROXY"] = HttpUrl;
        psi.Environment["ALL_PROXY"] = SocksUrl;
        psi.Environment["http_proxy"] = HttpUrl;
        psi.Environment["https_proxy"] = HttpUrl;
        psi.Environment["all_proxy"] = SocksUrl;
        psi.Environment["NO_PROXY"] = "localhost,127.0.0.1,::1";
        psi.Environment["no_proxy"] = "localhost,127.0.0.1,::1";

        // Java picks these up for every JVM it spawns (covers Minecraft and friends).
        psi.Environment["JAVA_TOOL_OPTIONS"] =
            $"-Dhttp.proxyHost=127.0.0.1 -Dhttp.proxyPort={MixedPort} " +
            $"-Dhttps.proxyHost=127.0.0.1 -Dhttps.proxyPort={MixedPort}";
    }

    /// <summary>Writes a Firefox profile whose only purpose is "use this proxy".</summary>
    public string WriteFirefoxProfile()
    {
        var dir = Path.Combine(AppPaths.CacheDir, "firefox-profile");
        Directory.CreateDirectory(dir);

        var prefs = new StringBuilder();
        prefs.AppendLine("// Generated by RouteScope. Safe to delete.");
        prefs.AppendLine("user_pref(\"network.proxy.type\", 1);");
        prefs.AppendLine($"user_pref(\"network.proxy.http\", \"127.0.0.1\");");
        prefs.AppendLine($"user_pref(\"network.proxy.http_port\", {MixedPort});");
        prefs.AppendLine($"user_pref(\"network.proxy.ssl\", \"127.0.0.1\");");
        prefs.AppendLine($"user_pref(\"network.proxy.ssl_port\", {MixedPort});");
        prefs.AppendLine($"user_pref(\"network.proxy.socks\", \"127.0.0.1\");");
        prefs.AppendLine($"user_pref(\"network.proxy.socks_port\", {MixedPort});");
        prefs.AppendLine("user_pref(\"network.proxy.socks_version\", 5);");
        prefs.AppendLine("user_pref(\"network.proxy.share_proxy_settings\", true);");
        prefs.AppendLine("user_pref(\"network.proxy.no_proxies_on\", \"localhost, 127.0.0.1\");");
        prefs.AppendLine("user_pref(\"network.proxy.allow_hijacking_localhost\", false);");
        prefs.AppendLine("user_pref(\"network.trr.mode\", 5);");

        File.WriteAllText(Path.Combine(dir, "user.js"), prefs.ToString(), new UTF8Encoding(false));
        return dir;
    }

    /// <summary>Writes a .cmd shim that sets the proxy variables, for tools started from a shell.</summary>
    public string WriteShellShim(string directory)
    {
        Directory.CreateDirectory(directory);
        var path = Path.Combine(directory, "routes-scope-env.cmd");
        var sb = new StringBuilder();
        sb.AppendLine("@echo off");
        sb.AppendLine("rem Generated by RouteScope. Run this before your tool to route it through the proxy.");
        sb.AppendLine($"set HTTP_PROXY={HttpUrl}");
        sb.AppendLine($"set HTTPS_PROXY={HttpUrl}");
        sb.AppendLine($"set ALL_PROXY={SocksUrl}");
        sb.AppendLine($"set http_proxy={HttpUrl}");
        sb.AppendLine($"set https_proxy={HttpUrl}");
        sb.AppendLine($"set all_proxy={SocksUrl}");
        sb.AppendLine("set NO_PROXY=localhost,127.0.0.1,::1");
        sb.AppendLine("%*");
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(false));
        return path;
    }

    private static bool IsFirefox(string exe) =>
        exe.Equals("firefox.exe", StringComparison.OrdinalIgnoreCase) ||
        exe.Equals("librewolf.exe", StringComparison.OrdinalIgnoreCase) ||
        exe.Equals("waterfox.exe", StringComparison.OrdinalIgnoreCase);

    private static readonly HashSet<string> KnownChromium = new(StringComparer.OrdinalIgnoreCase)
    {
        "chrome.exe", "msedge.exe", "brave.exe", "vivaldi.exe", "opera.exe",
        "thorium.exe", "yandex.exe", "chromium.exe", "arc.exe", "zen.exe",
    };

    /// <summary>
    /// Chromium browsers and Electron apps both understand <c>--proxy-server</c>. Electron is
    /// detected by the usual giveaways (app.asar, chrome_elf.dll, .pak resources) so the flag
    /// is only added where it is safe.
    /// </summary>
    public static bool IsChromiumFamily(string exePath)
    {
        var name = Path.GetFileName(exePath);
        if (KnownChromium.Contains(name)) return true;

        try
        {
            var dir = Path.GetDirectoryName(exePath);
            if (string.IsNullOrEmpty(dir)) return false;

            if (File.Exists(Path.Combine(dir, "chrome_elf.dll"))) return true;
            if (File.Exists(Path.Combine(dir, "resources", "app.asar"))) return true;
            if (File.Exists(Path.Combine(dir, "app.asar"))) return true;

            // Chromium ships locale .pak files next to the binary.
            foreach (var pak in new[] { "chrome_100_percent.pak", "resources.pak", "icudtl.dat" })
                if (File.Exists(Path.Combine(dir, pak))) return true;
        }
        catch { }
        return false;
    }
}
